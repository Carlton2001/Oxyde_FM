//! Bounded admission and eviction of disposable, recognized preview cache files.
use std::ffi::{OsStr, OsString};
use std::fs::File;
use std::io;
use std::os::windows::{ffi::OsStringExt, fs::MetadataExt, io::AsRawHandle};
use std::time::{Duration, Instant};
use windows::Win32::Foundation::{GENERIC_READ, GENERIC_WRITE, HANDLE};
use windows::Win32::Storage::FileSystem::{
    FileIdBothDirectoryInfo, FileIdBothDirectoryRestartInfo, GetFileInformationByHandle,
    GetFileInformationByHandleEx, BY_HANDLE_FILE_INFORMATION, DELETE, FILE_ID_BOTH_DIR_INFO,
};

const LEASE: &str = ".preview-cache-lock";

#[derive(Clone, Copy)]
pub(super) struct Policy {
    pub bytes: u64,
    pub entries: usize,
    pub entry_bytes: u64,
    pub scan_entries: usize,
    pub maintenance_time: Duration,
}
impl Default for Policy {
    fn default() -> Self {
        Self {
            bytes: 256 * 1024 * 1024,
            entries: 4096,
            entry_bytes: 4 * 1024 * 1024,
            scan_entries: 16384,
            maintenance_time: Duration::from_millis(500),
        }
    }
}

// These are the names currently generated by Oxyde. Unknown files are counted
// conservatively, but never evicted. Do not treat arbitrary PNG/JPEGs as owned.
pub(super) fn recognized(name: &OsStr) -> bool {
    let Some(name) = name.to_str() else {
        return false;
    };
    let stem = name
        .strip_suffix(".jpg")
        .or_else(|| name.strip_suffix("_small.png"))
        .or_else(|| name.strip_suffix("_large.png"));
    stem.is_some_and(|stem| {
        stem.len() == 64
            && stem
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
    })
}

fn recognized_staging(name: &OsStr) -> bool {
    let Some(name) = name.to_str().and_then(|name| name.strip_suffix(".tmp")) else {
        return false;
    };
    let mut parts = name.rsplitn(3, '.');
    let (Some(counter), Some(process), Some(stem)) = (parts.next(), parts.next(), parts.next())
    else {
        return false;
    };
    let decimal = |part: &str| !part.is_empty() && part.bytes().all(|byte| byte.is_ascii_digit());
    decimal(counter)
        && counter.parse::<u64>().is_ok()
        && decimal(process)
        && process.parse::<u32>().is_ok_and(|process| process != 0)
        && (recognized(OsStr::new(&format!("{stem}.jpg")))
            || recognized(OsStr::new(&format!("{stem}.png"))))
}

#[derive(Debug)]
struct Entry {
    name: OsString,
    bytes: u64,
    created: u64,
    modified: u64,
    id: u64,
    attributes: u32,
}

fn io_error(error: windows::core::Error) -> io::Error {
    io::Error::from_raw_os_error((error.code().0 as u32 & 0xffff) as i32)
}
fn deadline(start: Instant, policy: Policy) -> io::Result<()> {
    if start.elapsed() >= policy.maintenance_time {
        return Err(io::Error::new(
            io::ErrorKind::TimedOut,
            "Preview cache maintenance budget exceeded",
        ));
    }
    Ok(())
}

fn parse_batch(bytes: &[u8]) -> io::Result<Vec<Entry>> {
    let header = std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileName);
    let mut offset = 0usize;
    let mut entries = Vec::new();
    loop {
        if bytes.len() - offset < header {
            return Err(io::Error::other(
                "Incomplete preview cache directory record",
            ));
        }
        let record = &bytes[offset..];
        let u32_at = |at| u32::from_le_bytes(record[at..at + 4].try_into().unwrap());
        let u64_at = |at| u64::from_le_bytes(record[at..at + 8].try_into().unwrap());
        let next = u32_at(std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, NextEntryOffset)) as usize;
        let length = u32_at(std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileNameLength)) as usize;
        let end = if next == 0 { record.len() } else { next };
        if end > record.len()
            || end < header
            || (next != 0 && next % 8 != 0)
            || length == 0
            || length % 2 != 0
            || length > end - header
        {
            return Err(io::Error::other("Invalid preview cache directory record"));
        }
        let size = u64_at(std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, EndOfFile));
        if size > i64::MAX as u64 {
            return Err(io::Error::other("Invalid preview cache file length"));
        }
        let name: Vec<u16> = record[header..header + length]
            .chunks_exact(2)
            .map(|pair| u16::from_le_bytes([pair[0], pair[1]]))
            .collect();
        entries.push(Entry {
            name: OsString::from_wide(&name),
            bytes: size,
            created: u64_at(std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, CreationTime)),
            modified: u64_at(std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, LastWriteTime)),
            id: u64_at(std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileId)),
            attributes: u32_at(std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileAttributes)),
        });
        if next == 0 {
            return Ok(entries);
        }
        offset += next;
    }
}

fn scan(
    parent: &File,
    destination: &OsStr,
    temporary: &OsStr,
    policy: Policy,
    start: Instant,
) -> io::Result<(u64, usize, Vec<Entry>)> {
    let mut storage = vec![0u64; 64 * 1024 / 8];
    let mut restart = true;
    let mut visited = 0usize;
    let mut total = 0u64;
    let mut count = 0usize;
    let mut candidates = Vec::new();
    loop {
        deadline(start, policy)?;
        storage.fill(0);
        let result = unsafe {
            GetFileInformationByHandleEx(
                HANDLE(parent.as_raw_handle()),
                if restart {
                    FileIdBothDirectoryRestartInfo
                } else {
                    FileIdBothDirectoryInfo
                },
                storage.as_mut_ptr().cast(),
                std::mem::size_of_val(storage.as_slice()) as u32,
            )
        };
        restart = false;
        if let Err(error) = result {
            let error = io_error(error);
            if error.raw_os_error() == Some(18) {
                break;
            }
            return Err(error);
        }
        // The OS writes into initialized, owned storage aligned to eight bytes.
        // parse_batch validates every dynamic name and next-record boundary.
        let bytes = unsafe {
            std::slice::from_raw_parts(
                storage.as_ptr().cast::<u8>(),
                std::mem::size_of_val(storage.as_slice()),
            )
        };
        for entry in parse_batch(bytes)? {
            visited = visited
                .checked_add(1)
                .ok_or_else(|| io::Error::other("Preview cache scan overflow"))?;
            if visited > policy.scan_entries {
                return Err(io::Error::other("Preview cache scan limit exceeded"));
            }
            deadline(start, policy)?;
            if entry.name == "."
                || entry.name == ".."
                || entry.name == LEASE
                || entry.name == temporary
            {
                continue;
            }
            if entry.attributes & (0x10 | 0x400) != 0 {
                return Err(io::Error::other(
                    "Preview cache quota refuses directories and reparse entries",
                ));
            }
            if entry.name == destination {
                continue;
            }
            total = total
                .checked_add(entry.bytes)
                .ok_or_else(|| io::Error::other("Preview cache byte count overflow"))?;
            count = count
                .checked_add(1)
                .ok_or_else(|| io::Error::other("Preview cache entry count overflow"))?;
            if (recognized(&entry.name) || recognized_staging(&entry.name))
                && entry.attributes & 1 == 0
                && entry.id != 0
            {
                candidates.push(entry);
            }
        }
    }
    Ok((total, count, candidates))
}

fn evict(parent: &File, entry: &Entry) -> io::Result<bool> {
    let file = match super::windows_no_reparse::open_relative(
        parent,
        &entry.name,
        false,
        GENERIC_READ.0 | DELETE.0,
        0,
        1,
    ) {
        Ok(file) => file,
        Err(_) => return Ok(false), // An open reader/writer or changed object is protected.
    };
    let metadata = file.metadata()?;
    if !metadata.is_file()
        || metadata.file_attributes() & 0x400 != 0
        || metadata.permissions().readonly()
        || metadata.len() != entry.bytes
        || metadata.creation_time() != entry.created
        || metadata.last_write_time() != entry.modified
    {
        return Ok(false);
    }
    let mut information = BY_HANDLE_FILE_INFORMATION::default();
    unsafe { GetFileInformationByHandle(HANDLE(file.as_raw_handle()), &mut information) }
        .map_err(io_error)?;
    let id = (u64::from(information.nFileIndexHigh) << 32) | u64::from(information.nFileIndexLow);
    if id == 0 || id != entry.id {
        return Ok(false);
    }
    super::windows_file_moves::remove(&file)?;
    drop(file);
    Ok(true)
}

// Return the exclusive lease so the caller keeps it through native publication.
pub(super) fn admit(
    parent: &File,
    destination: &OsStr,
    temporary: &OsStr,
    incoming: &File,
    policy: Policy,
) -> io::Result<File> {
    let incoming_bytes = incoming.metadata()?.len();
    if incoming_bytes > policy.entry_bytes || incoming_bytes > policy.bytes || policy.entries == 0 {
        return Err(io::Error::other(
            "Preview cache entry exceeds its disk budget",
        ));
    }
    let lease = super::windows_no_reparse::open_relative(
        parent,
        OsStr::new(LEASE),
        false,
        GENERIC_READ.0 | GENERIC_WRITE.0,
        0,
        3,
    )
    .map_err(|error| {
        if matches!(error.raw_os_error(), Some(32 | 33)) {
            io::Error::new(io::ErrorKind::WouldBlock, error)
        } else {
            error
        }
    })?;
    let start = Instant::now();
    let (mut bytes, mut entries, mut candidates) =
        scan(parent, destination, temporary, policy, start)?;
    let fits = |entries: usize, bytes: u64| {
        entries
            .checked_add(1)
            .is_some_and(|entries| entries <= policy.entries)
            && bytes
                .checked_add(incoming_bytes)
                .is_some_and(|bytes| bytes <= policy.bytes)
    };
    if fits(entries, bytes) {
        return Ok(lease);
    }
    candidates.sort_by(|a, b| {
        recognized(&a.name)
            .cmp(&recognized(&b.name))
            .then_with(|| a.modified.cmp(&b.modified))
            .then_with(|| a.name.cmp(&b.name))
    });
    for entry in candidates {
        deadline(start, policy)?;
        if evict(parent, &entry).unwrap_or(false) {
            bytes -= entry.bytes;
            entries -= 1;
        }
        if fits(entries, bytes) {
            return Ok(lease);
        }
    }
    Err(io::Error::other(
        "Preview cache disk budget is occupied by protected entries",
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::Path;

    fn raw_record(name: &[u16]) -> Vec<u8> {
        let header = std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileName);
        let mut bytes = vec![0; header + name.len() * 2];
        let at = std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileNameLength);
        bytes[at..at + 4].copy_from_slice(&(name.len() as u32 * 2).to_le_bytes());
        for (index, code) in name.iter().enumerate() {
            bytes[header + index * 2..header + index * 2 + 2].copy_from_slice(&code.to_le_bytes());
        }
        bytes
    }

    #[test]
    fn directory_records_validate_unicode_names_and_multiple_record_boundaries() {
        let mut first = raw_record(&"cache-é".encode_utf16().collect::<Vec<_>>());
        let aligned = first.len().div_ceil(8) * 8;
        first.resize(aligned, 0);
        first[..4].copy_from_slice(&(aligned as u32).to_le_bytes());
        first.extend(raw_record(
            &"miniature-漢字".encode_utf16().collect::<Vec<_>>(),
        ));
        let records = parse_batch(&first).unwrap();
        assert_eq!(records.len(), 2);
        assert_eq!(records[0].name, "cache-é");
        assert_eq!(records[1].name, "miniature-漢字");
    }

    #[test]
    fn malformed_directory_records_are_refused_without_out_of_bounds_reads() {
        let header = std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileName);
        for length in 0..header {
            assert!(parse_batch(&vec![0; length]).is_err());
        }
        for (field, value) in [
            (
                std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileNameLength),
                0u32,
            ),
            (
                std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileNameLength),
                3,
            ),
            (
                std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, FileNameLength),
                u32::MAX,
            ),
            (0, 1),
            (0, header as u32),
            (0, u32::MAX),
        ] {
            let mut bytes = raw_record(&[b'a' as u16]);
            bytes[field..field + 4].copy_from_slice(&value.to_le_bytes());
            assert!(parse_batch(&bytes).is_err());
        }
        let mut bytes = raw_record(&[b'a' as u16]);
        let at = std::mem::offset_of!(FILE_ID_BOTH_DIR_INFO, EndOfFile);
        bytes[at..at + 8].copy_from_slice(&(-1i64).to_le_bytes());
        assert!(parse_batch(&bytes).is_err());
    }

    fn snapshot(root: &Path) -> (File, Entry) {
        let parent = super::super::windows_file_moves::hold_parent(root).unwrap();
        let (_, _, mut entries) = scan(
            &parent,
            OsStr::new("incoming.png"),
            OsStr::new("incoming.tmp"),
            Policy::default(),
            Instant::now(),
        )
        .unwrap();
        assert_eq!(entries.len(), 1);
        (parent, entries.remove(0))
    }

    #[test]
    fn eviction_preserves_an_entry_modified_after_the_snapshot() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join(format!("{:064x}_small.png", 1));
        fs::write(&path, b"old").unwrap();
        let (parent, entry) = snapshot(root.path());
        fs::write(&path, b"modified since scan").unwrap();
        assert!(!evict(&parent, &entry).unwrap());
        assert_eq!(fs::read(path).unwrap(), b"modified since scan");
    }

    #[test]
    fn eviction_preserves_a_replacement_with_the_same_length() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join(format!("{:064x}_small.png", 1));
        fs::write(&path, b"old").unwrap();
        let (parent, entry) = snapshot(root.path());
        let retained = File::open(&path).unwrap();
        let old = root.path().join("old_marker");
        fs::rename(&path, &old).unwrap();
        fs::write(&path, b"new").unwrap();
        assert!(!evict(&parent, &entry).unwrap());
        assert_eq!(fs::read(&path).unwrap(), b"new");
        assert_eq!(fs::read(old).unwrap(), b"old");
        drop(retained);
    }
}
